// Generates src/ucsSynonyms.json — the UCS's OWN synonyms, one row per subcategory —
// from the UCS category JSONs (the DATATYPE.soundfx.UCS repo, a sibling Softapp).
// Run:  node scripts/gen-ucs-synonyms.mjs [path/to/DATATYPE.soundfx.UCS]
//
// That is the first ring of the synonym library: the words the UCS spreadsheet itself
// files under each subcategory ("Abbey", "Castle", "Victorian" under DOORS › ANTIQUE),
// plus the producer vocabulary in producer_synonyms.json ("808", "bd" under the drum
// MISC buckets). The second ring — words for those words ("sedan" for "car") — is the
// hand-kept src/ucsThesaurus.json; this script never touches it.
//
// KEEPS GOING ON ERRORS. A category file that will not read or parse is skipped with a
// warning and the rest are still written; a missing producer_synonyms.json is a warning,
// not a stop. Only when NOTHING usable was read does it refuse to write, so a bad path
// can never replace a good library with an empty one.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
// scripts → Web_Front → SCANALYZER.Like.audio → SCANALYZER_SUITE → Softapps
const ucsDir = resolve(process.argv[2] || process.env.UCS_DIR || join(here, '../../../../DATATYPE/DATATYPE.soundfx.UCS'));
const outFile = join(here, '../src/ucsSynonyms.json');

const warnings = [];
const warn = (m) => { warnings.push(m); console.warn(`warn: ${m}`); };

/** Lowercase, trim, single spaces; '' for anything that is not a usable word. */
function clean(w) {
  if (typeof w !== 'string') return '';
  return w.toLowerCase().replace(/\s+/g, ' ').trim().replace(/[.,;:]+$/, '');
}

const catDir = join(ucsDir, 'categories');
let files = [];
try {
  files = readdirSync(catDir).filter(f => f.endsWith('.json') && f !== 'index.json').sort();
} catch (e) {
  console.error(`error: cannot list ${catDir}: ${e.message}`);
  process.exit(1);
}

// Producer vocabulary, keyed by category_id. Optional.
let producer = {};
const producerFile = join(ucsDir, 'producer_synonyms.json');
if (existsSync(producerFile)) {
  try { producer = JSON.parse(readFileSync(producerFile, 'utf8')).additions || {}; }
  catch (e) { warn(`producer_synonyms.json unreadable (${e.message}) — skipped`); }
} else {
  warn('no producer_synonyms.json — producer vocabulary skipped');
}

const rows = [];
const versions = new Set();
for (const f of files) {
  let cat;
  try { cat = JSON.parse(readFileSync(join(catDir, f), 'utf8')); }
  catch (e) { warn(`${f} unreadable (${e.message}) — skipped`); continue; }
  if (!cat || typeof cat.category !== 'string' || !Array.isArray(cat.subcategories)) {
    warn(`${f} has no category/subcategories — skipped`); continue;
  }
  if (cat.version) versions.add(String(cat.version));
  for (const s of cat.subcategories) {
    if (!s || typeof s.subcategory !== 'string') { warn(`${f}: a subcategory without a name — skipped`); continue; }
    const id = typeof s.category_id === 'string' ? s.category_id : '';
    const words = new Set();
    for (const w of [...(Array.isArray(s.synonyms) ? s.synonyms : []), ...(producer[id] || [])]) {
      const c = clean(w);
      if (c) words.add(c);
    }
    rows.push([cat.category, s.subcategory, id, [...words].sort()]);
  }
}

if (rows.length === 0) {
  console.error(`error: no subcategories read from ${catDir} — ${outFile} left as it was`);
  process.exit(1);
}

rows.sort((a, b) => (a[0] + '\t' + a[1]).localeCompare(b[0] + '\t' + b[1]));
const out = {
  _generated: 'GENERATED by scripts/gen-ucs-synonyms.mjs from DATATYPE.soundfx.UCS/categories/*.json + producer_synonyms.json — do not edit by hand. Row = [CATEGORY, SUBCATEGORY, category_id, synonyms].',
  versions: [...versions].sort(),
  subcategories: rows,
};
// One row per line: diffs stay readable when the taxonomy moves.
const body = rows.map(r => '    ' + JSON.stringify(r)).join(',\n');
writeFileSync(outFile,
  `{\n  "_generated": ${JSON.stringify(out._generated)},\n  "versions": ${JSON.stringify(out.versions)},\n  "subcategories": [\n${body}\n  ]\n}\n`);
const nWords = new Set(rows.flatMap(r => r[3])).size;
console.log(`wrote ${outFile}: ${rows.length} subcategories, ${nWords} distinct words` +
  (warnings.length ? `, ${warnings.length} warning(s)` : ''));
